// ============================================================
// Route Protection Proxy (formerly middleware.ts)
// Validates session on every request using Supabase SSR
// Next.js 16+ uses proxy.ts convention
// ============================================================

import { type NextRequest } from "next/server";
import { updateSession } from "@/lib/supabase/middleware";

export async function proxy(request: NextRequest) {
  return await updateSession(request);
}

export const config = {
  matcher: [
    /*
     * Match all request paths EXCEPT:
     * - _next/static (static files)
     * - _next/image (image optimization)
     * - favicon.ico
     * - Any static file extensions
     * - auth callback routes (must be accessible pre-auth)
     */
    "/((?!_next/static|_next/image|favicon.ico|.*\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)",
  ],
};
